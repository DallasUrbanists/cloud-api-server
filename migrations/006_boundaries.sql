BEGIN;

CREATE FUNCTION boundaries_valid_geometry(value jsonb)
RETURNS boolean LANGUAGE plpgsql IMMUTABLE STRICT AS $$
DECLARE polygon jsonb; polygons jsonb; ring jsonb; position jsonb;
BEGIN
  IF jsonb_typeof(value) <> 'object' THEN RETURN false; END IF;
  IF value ->> 'type' = 'Polygon' THEN
    polygons := jsonb_build_array(value -> 'coordinates');
  ELSIF value ->> 'type' = 'MultiPolygon' AND jsonb_typeof(value -> 'coordinates') = 'array' THEN
    polygons := value -> 'coordinates';
  ELSE RETURN false;
  END IF;
  IF jsonb_array_length(polygons) = 0 THEN RETURN false; END IF;
  FOR polygon IN SELECT jsonb_array_elements(polygons) LOOP
    IF NOT representatives_valid_polygon(jsonb_build_object('type', 'Polygon', 'coordinates', polygon)) THEN RETURN false; END IF;
    FOR ring IN SELECT jsonb_array_elements(polygon) LOOP
      FOR position IN SELECT jsonb_array_elements(ring) LOOP
        IF abs((position ->> 0)::numeric) > 180 OR abs((position ->> 1)::numeric) > 90 THEN RETURN false; END IF;
      END LOOP;
    END LOOP;
  END LOOP;
  RETURN true;
END $$;

CREATE FUNCTION boundaries_extent(value jsonb)
RETURNS box LANGUAGE plpgsql IMMUTABLE STRICT AS $$
DECLARE polygons jsonb; polygon jsonb; ring jsonb; position jsonb;
  xmin double precision := 180; ymin double precision := 90;
  xmax double precision := -180; ymax double precision := -90;
  longitude double precision; latitude double precision;
BEGIN
  IF NOT boundaries_valid_geometry(value) THEN RETURN NULL; END IF;
  polygons := CASE WHEN value ->> 'type' = 'Polygon'
    THEN jsonb_build_array(value -> 'coordinates') ELSE value -> 'coordinates' END;
  FOR polygon IN SELECT jsonb_array_elements(polygons) LOOP
    FOR ring IN SELECT jsonb_array_elements(polygon) LOOP
      FOR position IN SELECT jsonb_array_elements(ring) LOOP
        longitude := (position ->> 0)::double precision;
        latitude := (position ->> 1)::double precision;
        xmin := least(xmin, longitude); xmax := greatest(xmax, longitude);
        ymin := least(ymin, latitude); ymax := greatest(ymax, latitude);
      END LOOP;
    END LOOP;
  END LOOP;
  RETURN box(point(xmin, ymin), point(xmax, ymax));
END $$;

CREATE FUNCTION boundaries_valid_service(value jsonb)
RETURNS boolean LANGUAGE plpgsql IMMUTABLE STRICT AS $$
BEGIN
  RETURN COALESCE(jsonb_typeof(value) = 'object'
    AND jsonb_typeof(value -> 'file') = 'string'
    AND (value ->> 'file') ~ '^[A-Za-z][A-Za-z0-9_-]*\.js$'
    AND jsonb_typeof(value -> 'function') = 'string'
    AND (value ->> 'function') ~ '^[A-Za-z_$][A-Za-z0-9_$]*$'
    AND jsonb_typeof(value -> 'params') = 'object'
    AND value - ARRAY['file', 'function', 'params'] = '{}'::jsonb, false);
END $$;

CREATE TABLE boundaries (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_name text NOT NULL CHECK (btrim(entity_name) <> ''),
  body_name text,
  district_name text,
  shape jsonb CHECK (boundaries_valid_geometry(shape)),
  shape_box box GENERATED ALWAYS AS (boundaries_extent(shape)) STORED,
  -- Unknown geometry is different from an intentionally address-only boundary.
  shape_pending boolean NOT NULL DEFAULT false,
  cities text[] NOT NULL DEFAULT '{}',
  counties text[] NOT NULL DEFAULT '{}',
  zips text[] NOT NULL DEFAULT '{}',
  states text[] NOT NULL DEFAULT '{}',
  description text NOT NULL DEFAULT '',
  when_to_contact text NOT NULL DEFAULT '',
  shape_service jsonb CHECK (boundaries_valid_service(shape_service)),
  research_service jsonb CHECK (boundaries_valid_service(research_service)),
  effective_date date,
  expiration_date date,
  last_shape_sync timestamptz CHECK (isfinite(last_shape_sync)),
  last_research_sync timestamptz CHECK (isfinite(last_research_sync)),
  last_shape_success timestamptz CHECK (isfinite(last_shape_success)),
  last_research_success timestamptz CHECK (isfinite(last_research_success)),
  shape_sync_ttl integer NOT NULL DEFAULT 365 CHECK (shape_sync_ttl > 0),
  research_sync_ttl integer NOT NULL DEFAULT 60 CHECK (research_sync_ttl > 0),
  shape_retry_after timestamptz,
  research_retry_after timestamptz,
  source_key text UNIQUE,
  CHECK (effective_date IS NULL OR effective_date BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
  CHECK (expiration_date IS NULL OR expiration_date BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
  CHECK (effective_date IS NULL OR expiration_date IS NULL OR effective_date < expiration_date),
  CHECK (array_position(cities, NULL) IS NULL AND array_position(counties, NULL) IS NULL
    AND array_position(zips, NULL) IS NULL AND array_position(states, NULL) IS NULL)
);
CREATE INDEX boundaries_names ON boundaries (lower(entity_name), lower(body_name), lower(district_name));
CREATE INDEX boundaries_shape_box ON boundaries USING gist(shape_box);
CREATE INDEX boundaries_cities ON boundaries USING gin (cities);
CREATE INDEX boundaries_counties ON boundaries USING gin (counties);
CREATE INDEX boundaries_zips ON boundaries USING gin (zips);
CREATE INDEX boundaries_states ON boundaries USING gin (states);

ALTER TABLE representatives
  ADD COLUMN boundary_id integer REFERENCES boundaries(id) ON DELETE RESTRICT,
  ADD COLUMN research_service jsonb CHECK (boundaries_valid_service(research_service)),
  ADD COLUMN last_research_sync timestamptz CHECK (isfinite(last_research_sync)),
  ADD COLUMN last_research_success timestamptz CHECK (isfinite(last_research_success)),
  ADD COLUMN research_sync_ttl integer NOT NULL DEFAULT 60 CHECK (research_sync_ttl > 0),
  ADD COLUMN research_retry_after timestamptz,
  ADD COLUMN source_key text;

LOCK TABLE representatives IN SHARE ROW EXCLUSIVE MODE;
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM representatives GROUP BY COALESCE(NULLIF(btrim(entity), ''), 'Unknown jurisdiction'), body, district
    HAVING count(DISTINCT district_bounds::text) > 1
      OR count(DISTINCT NULLIF(district_description, '')) > 1
  ) THEN
    RAISE EXCEPTION 'Conflicting jurisdiction geometry or descriptions; resolve before boundary backfill';
  END IF;
END $$;

INSERT INTO boundaries (entity_name, body_name, district_name, shape, shape_pending, description)
SELECT COALESCE(NULLIF(btrim(entity), ''), 'Unknown jurisdiction'), body, district,
  (max(district_bounds::text))::jsonb,
  bool_and(district_bounds IS NULL), COALESCE(max(district_description), '')
FROM representatives GROUP BY COALESCE(NULLIF(btrim(entity), ''), 'Unknown jurisdiction'), body, district;

UPDATE representatives r SET boundary_id = b.id FROM boundaries b
WHERE b.entity_name = COALESCE(NULLIF(btrim(r.entity), ''), 'Unknown jurisdiction')
  AND b.body_name IS NOT DISTINCT FROM r.body
  AND b.district_name IS NOT DISTINCT FROM r.district;
ALTER TABLE representatives ALTER COLUMN boundary_id SET NOT NULL;
CREATE INDEX representatives_boundary ON representatives(boundary_id);
CREATE UNIQUE INDEX representatives_source ON representatives(boundary_id, source_key) WHERE source_key IS NOT NULL AND "end" IS NULL;
ALTER TABLE representatives DROP COLUMN entity, DROP COLUMN body, DROP COLUMN district,
  DROP COLUMN district_description, DROP COLUMN district_bounds;

CREATE TABLE boundary_sync_jobs (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  scope_id integer NOT NULL REFERENCES boundaries(id),
  target_type text NOT NULL CHECK (target_type IN ('boundary', 'representative')),
  target_id integer NOT NULL,
  shape_requested boolean NOT NULL DEFAULT false,
  research_requested boolean NOT NULL DEFAULT false,
  force_sync boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'succeeded', 'failed')),
  lease_token text,
  lease_until timestamptz,
  available_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at timestamptz,
  error_code text,
  attempts integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX boundary_sync_active_scope ON boundary_sync_jobs(scope_id) WHERE status IN ('queued', 'running');
CREATE INDEX boundary_sync_queue ON boundary_sync_jobs(status, available_at, lease_until);
CREATE TABLE boundary_sync_budgets (
  bucket text PRIMARY KEY,
  window_start timestamptz NOT NULL,
  requests integer NOT NULL CHECK (requests >= 0)
);
CREATE TABLE boundary_research_evidence (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  boundary_id integer NOT NULL REFERENCES boundaries(id),
  representative_id integer REFERENCES representatives(id),
  job_id bigint REFERENCES boundary_sync_jobs(id),
  source_urls jsonb NOT NULL CHECK (jsonb_typeof(source_urls) = 'array'),
  retrieved_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  outcome text NOT NULL CHECK (outcome IN ('applied', 'review_required')),
  proposal jsonb NOT NULL
);
COMMIT;
